// Derive public client types from PostgreSQL after applying every migration.
// The test bootstrap models Supabase-owned schemas; it is never a production migration.
import { writeFile, readFile } from 'node:fs/promises';
import { createTestDatabase } from '../tests/helpers/database.mjs';

const db = await createTestDatabase();
try {
  const enums = (
    await db.query(`select t.typname, e.enumlabel from pg_type t
    join pg_namespace n on n.oid=t.typnamespace join pg_enum e on e.enumtypid=t.oid
    where n.nspname='public' order by t.typname,e.enumsortorder`)
  ).rows;
  const enumNames = new Set(enums.map((e) => e.typname));
  const columns = (
    await db.query(`select table_name,column_name,is_nullable,column_default,udt_name
    from information_schema.columns where table_schema='public' order by table_name,ordinal_position`)
  ).rows;
  const relationships = (
    await db.query(`select c.conname,src.relname as source,dst.relname as target,
    exists(select 1 from pg_index i where i.indrelid=src.oid and i.indisunique and i.indpred is null
      and i.indexprs is null and i.indkey::smallint[] <@ c.conkey) as is_one_to_one,
    array(select a.attname from unnest(c.conkey) with ordinality k(num,ord)
      join pg_attribute a on a.attrelid=c.conrelid and a.attnum=k.num order by k.ord) as columns,
    array(select a.attname from unnest(c.confkey) with ordinality k(num,ord)
      join pg_attribute a on a.attrelid=c.confrelid and a.attnum=k.num order by k.ord) as referenced_columns
    from pg_constraint c join pg_class src on src.oid=c.conrelid
    join pg_class dst on dst.oid=c.confrelid join pg_namespace ns on ns.oid=src.relnamespace
    join pg_namespace nd on nd.oid=dst.relnamespace
    where c.contype='f' and ns.nspname='public' and nd.nspname='public' order by src.relname,c.conname`)
  ).rows;
  const type = (name) =>
    enumNames.has(name)
      ? `Database['public']['Enums'][${JSON.stringify(name)}]`
      : name.startsWith('_')
        ? `${type(name.slice(1))}[]`
        : ['int2', 'int4', 'int8', 'numeric', 'float4', 'float8'].includes(name)
          ? 'number'
          : name === 'bool'
            ? 'boolean'
            : ['json', 'jsonb'].includes(name)
              ? 'Json'
              : 'string';
  let out = `// Generated by npm run db:types from migrated PostgreSQL. Do not edit manually.\n`;
  out += `export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\n`;
  out += `export type Database = { public: { Tables: {\n`;
  for (const table of [...new Set(columns.map((c) => c.table_name))]) {
    out += `${JSON.stringify(table)}: {\n`;
    for (const shape of ['Row', 'Insert', 'Update']) {
      out += `${shape}: {\n`;
      for (const c of columns.filter((c) => c.table_name === table)) {
        const optional =
          shape === 'Update' ||
          (shape === 'Insert' && (c.column_default !== null || c.is_nullable === 'YES'));
        out += `${JSON.stringify(c.column_name)}${optional ? '?' : ''}: ${type(c.udt_name)}${c.is_nullable === 'YES' ? ' | null' : ''};\n`;
      }
      out += '};\n';
    }
    out += 'Relationships: [\n';
    for (const r of relationships.filter((r) => r.source === table)) {
      out += `{ foreignKeyName: ${JSON.stringify(r.conname)}; columns: ${JSON.stringify(r.columns)}; isOneToOne: ${r.is_one_to_one}; referencedRelation: ${JSON.stringify(r.target)}; referencedColumns: ${JSON.stringify(r.referenced_columns)} },\n`;
    }
    out += '];\n};\n';
  }
  out += `}; Views: { [_ in never]: never }; Functions: {
    platform_schema_version: { Args: Record<string, never>; Returns: number };
    save_website_mode:{Args:{tenant:string;mode:Database['public']['Enums']['website_mode'];message:string;reopening:string|null;expected:string};Returns:undefined};
    restaurant_sales_report:{Args:{p_restaurant:string;p_from:string;p_to:string};Returns:Json};
    restaurant_activity_log:{Args:{p_restaurant:string;p_from:string;p_to:string;p_entity:string|null;p_action:string|null;p_actor:string|null;p_page:number};Returns:Json};
    create_support_ticket:{Args:{p_restaurant:string;p_input:Json;p_token:string;p_order_token:string|null};Returns:Json};
    read_support_ticket:{Args:{p_restaurant:string;p_reference:string;p_token:string|null;p_page:number};Returns:Json};
    reply_support_ticket:{Args:{p_restaurant:string;p_reference:string;p_token:string|null;p_body:string;p_internal:boolean;p_nonce:string};Returns:string};
    support_assignees:{Args:{p_restaurant:string};Returns:Json};
    support_attachment:{Args:{p_restaurant:string;p_ticket:string;p_message:string|null;p_attachment:string|null;p_token:string|null;p_file:Json|null};Returns:Json};
    quote_cart: {Args:{p_restaurant:string;p_items:Json;p_method:string;p_zone:string|null};Returns:Json};
    place_customer_order: {Args:{p_restaurant:string;p_items:Json;p_checkout:Json;p_token:string;p_expected_total:number};Returns:Json};
    read_order_capability: {Args:{p_restaurant:string;p_reference:string;p_token:string};Returns:Json};
    save_customer_profile: {Args:{p_restaurant:string;p_name:string;p_phone:string};Returns:string|null};
    save_customer_address: {Args:{p_restaurant:string;p_address:string|null;p_label:string;p_line:string;p_area:string;p_city:string;p_instructions:string;p_default:boolean};Returns:string};
    resolve_guest_access: { Args: {p_kind: string; p_reference: string; p_token: string}; Returns: {resource_id: string; restaurant_id: string}[] };
    current_staff_access: { Args: {p_restaurant:string}; Returns: Json };
    create_staff_invitation: { Args: {p_restaurant:string;p_email:string;p_role:string;p_token_hash:string}; Returns:string };
    accept_staff_invitation: {Args:{p_token:string};Returns:string};
    revoke_staff_invitation: {Args:{p_restaurant:string;p_invitation:string};Returns:undefined};
    manage_staff_member: {Args:{p_restaurant:string;p_member:string;p_role:string;p_status:Database['public']['Enums']['membership_status']};Returns:undefined};
    set_staff_roles: {Args:{p_restaurant:string;p_member:string;p_role:string;p_extra_roles:string[];p_status:Database['public']['Enums']['membership_status']};Returns:undefined};
    save_custom_role: {Args:{p_restaurant:string;p_role:string|null;p_name:string;p_slug:string;p_permissions:string[]};Returns:string};
    bootstrap_restaurant_owner: {Args:{p_restaurant:string;p_owner:string};Returns:undefined};
    save_menu_variant: {Args:{p_restaurant:string;p_product:string;p_variant:string|null;p_name:string;p_price:number;p_active:boolean;p_default:boolean;p_sort:number};Returns:string};
  }; Enums: {\n`;
  for (const name of enumNames)
    out += `${JSON.stringify(name)}: ${enums
      .filter((e) => e.typname === name)
      .map((e) => JSON.stringify(e.enumlabel))
      .join(' | ')};\n`;
  out += '}; CompositeTypes: { [_ in never]: never } } };\n';
  // Use the project formatter so the committed output is deterministic.
  const { format } = await import('prettier');
  out = await format(out, { parser: 'typescript', singleQuote: true, printWidth: 100 });
  const target = new URL('../src/lib/supabase/database.types.ts', import.meta.url);
  if (process.argv.includes('--check')) {
    if ((await readFile(target, 'utf8')) !== out)
      throw new Error('Database types are stale. Run npm run db:types.');
    console.log('Database types match migrated PostgreSQL.');
  } else {
    await writeFile(target, out);
    console.log('Generated public database types.');
  }
} finally {
  await db.close();
}
