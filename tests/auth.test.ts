import test from 'node:test';
import assert from 'node:assert/strict';
import {
  safeNext,
  registrationSchema,
  loginSchema,
  tokenSchema,
} from '../src/features/auth/validation.ts';
import { visibleModule } from '../src/features/auth/permissions.ts';
test('redirects reject external origins, encoded separators, control characters and token queries', () => {
  for (const value of [
    'https://evil.test',
    '//evil.test',
    '/\\evil.test',
    '/%2f/evil.test',
    '/admin%0a',
    '/admin?token=secret',
    '/invite#token=secret',
    '/admin/%252f',
    '/auth/callback',
    '/menu',
    null,
  ])
    assert.equal(safeNext(value), '/account');
  assert.equal(safeNext('/admin/staff'), '/admin/staff');
  assert.equal(safeNext('/invite'), '/invite');
});
test('registration requires a long password and matching confirmation', () => {
  const valid = {
    name: 'Customer',
    email: 'customer@example.com',
    password: 'a unique long phrase',
    confirmPassword: 'a unique long phrase',
  };
  assert.ok(registrationSchema.safeParse(valid).success);
  assert.ok(
    !registrationSchema.safeParse({ ...valid, password: 'short', confirmPassword: 'short' })
      .success,
  );
  assert.ok(!registrationSchema.safeParse({ ...valid, confirmPassword: 'different' }).success);
  assert.ok(!registrationSchema.safeParse({ ...valid, name: ' ' }).success);
});
test('login preserves password whitespace and normalizes email case', () => {
  assert.deepEqual(loginSchema.parse({ email: 'Customer@Example.com', password: ' password ' }), {
    email: 'customer@example.com',
    password: ' password ',
  });
});
test('invitation tokens require 32 cryptographically generated bytes encoded as lowercase hex', () => {
  assert.ok(tokenSchema.safeParse('a'.repeat(64)).success);
  for (const bad of ['a'.repeat(63), 'z'.repeat(64), 'A'.repeat(64), ''])
    assert.ok(!tokenSchema.safeParse(bad).success);
});
test('navigation only exposes modules allowed by current permissions', () => {
  assert.ok(visibleModule('support', ['support.read']));
  assert.ok(!visibleModule('menu', ['support.read']));
  assert.ok(!visibleModule('staff', ['menu.read']));
  assert.ok(visibleModule('menu', ['menu.manage']));
});
